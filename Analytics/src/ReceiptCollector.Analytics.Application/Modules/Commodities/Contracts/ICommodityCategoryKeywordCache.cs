using ReceiptCollector.Analytics.Domain.Modules.Commodities;

namespace ReceiptCollector.Analytics.Application.Modules.Commodities.Contracts;

/// <summary>
/// In-memory кэш слов категоризации (ADR-035, решение E1, п. 6): singleton с неизменяемым
/// снимком <see cref="CommodityCategoryKeywordSnapshot"/>. Читатели (провайдер подсказок, задача 05)
/// берут снимок без обращений к БД и без блокировок (NFR-1); инвалидация — полное перечитывание
/// после commit мутации (<see cref="RefreshAsync"/>) и ленивое перечитывание по «грязному» флагу
/// (NFR-4, без рестарта).
/// Реализация — Infrastructure (<c>InMemoryCommodityCategoryKeywordCache</c>), регистрация —
/// Singleton (прецедент <see cref="ICommodityCategoryCache"/> и ADR-019).
/// <para>
/// Семантика деградации (ADR-035 п. 6): сбой перечитывания НИКОГДА не бросает на горячий путь —
/// старый снимок остаётся валидным и продолжает отдаваться, кэш помечается «грязным» и повторит
/// перечитывание на следующем чтении. Мутация к тому моменту уже зафиксирована в БД
/// (БД — источник правды), поэтому расхождение временно и самовосстанавливается.
/// </para>
/// <para>
/// Мультиэкземплярность не поддерживается (зафиксированное ограничение single-instance, ADR-027 D12):
/// правка на одном инстансе не инвалидирует кэш другого; координация (Redis/<c>LISTEN/NOTIFY</c>) —
/// вне области (ADR-035, E4).
/// </para>
/// </summary>
public interface ICommodityCategoryKeywordCache
{
    /// <summary>
    /// Текущий снимок слов. На «чистом» состоянии — чтение ссылки без блокировок и без БД
    /// (горячий путь, NFR-1). На «грязном» флаге (состояние до прогрева или после сбоя
    /// перечитывания) — перечитывание с double-check под семафором записи; при повторном сбое
    /// возвращает старый снимок без исключения (деградация, ADR-035 п. 6).
    /// </summary>
    CommodityCategoryKeywordSnapshot GetSnapshot();

    /// <summary>
    /// Полное перечитывание таблицы (один <c>SELECT</c>) и атомарная подмена ссылки на снимок.
    /// Вызывается прогревом при старте и сервисом после успешного commit мутации (ADR-035 п. 6).
    /// Сбой перечитывания не бросается вызывающему: фиксируется предупреждением, «грязный» флаг
    /// остаётся выставленным, старый снимок продолжает использоваться — мутация уже успешна
    /// и не должна отменяться из-за сбоя инвалидации (NFR-4).
    /// </summary>
    Task RefreshAsync(CancellationToken cancellationToken = default);
}
