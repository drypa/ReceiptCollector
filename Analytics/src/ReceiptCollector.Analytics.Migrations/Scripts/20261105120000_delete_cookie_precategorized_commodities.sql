-- Очистка очереди предкатегоризации от строк с «печенье» в названии.
-- Промпт ИИ раньше рекомендовал категоризировать печенье в «Конфеты» (Sweets),
-- после уточнения промпта (печенье → Кондитерские изделия, Confectionery)
-- старые предложения устарели. Удаление строк (и proposed, и applied) позволяет
-- фоновой предкатегоризации (ADR-027) заново предложить категорию, а ИИ —
-- переосмыслить название по обновлённому промпту.
-- Раннер обеспечивает идемпотентность: повторный запуск скрипта не выполняется
-- (запись в migration_scripts_history). Удаление безусловное по наименованию,
-- критичных зависимостей от строки нет (FK на merchants — каскад от магазина,
-- а не от этой таблицы). commodities.category_id не трогаем: уже присвоенные
-- категории товаров имеют приоритет «existing» в конвейере (ADR-028 п. 9) и
-- переопределяются только вручную или сбросом.

DELETE FROM precategorized_commodities
WHERE name ILIKE '%печенье%';
