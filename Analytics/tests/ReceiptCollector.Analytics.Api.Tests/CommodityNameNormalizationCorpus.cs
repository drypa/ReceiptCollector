namespace ReceiptCollector.Analytics.Api.Tests;

/// <summary>
/// Golden corpus правила очистки названий товаров (ADR-034 п. 1; задача T-03).
/// <para>
/// Единственный источник кейсов <c>(сырое имя, ожидаемый ключ)</c> для обоих тестов:
/// юнит-тестов <c>CommodityNameNormalizerTests</c> и паритетного теста миграции
/// <c>PrecategorizedNormalizedNameMigrationTests</c> (SQL-backfill ↔ C#).
/// Ожидания здесь не дублируются: новые кейсы добавляются только в этот список.
/// </para>
/// <para>
/// Состав: все строки таблицы примеров ADR-034 п. 1, границы правила (5/6 цифр,
/// кластеры хвостовых кодов, ведущий мусор <c>*#№</c>, fallback «имя только из кода»)
/// и зафиксированные ограничения (дефис и запятая внутри номера, код в середине).
/// </para>
/// </summary>
internal static class CommodityNameNormalizationCorpus
{
    /// <summary>Кейсы corpus: (вход — сырое имя, ожидание — результат <c>NormalizeName</c>).</summary>
    public static IReadOnlyList<(string Input, string Expected)> Cases { get; } =
    [
        // Четыре примера из задачи (ADR-034 п. 1): ведущий EAN/артикул и хвостовой EAN снимаются,
        // «смысловые» короткие числа (256г, (3сл, 4р)) сохраняются.
        ("2417268000006 ПИРОГ С ВИШНЕЙ ПО РЕ", "пирог с вишней по ре"),
        ("2444436000001 СЕТ ДУЭТ 256г", "сет дуэт 256г"),
        ("*3455614 РЖ.КРАЙ Хлеб нар.300г", "рж.край хлеб нар.300г"),
        ("2195738 Туалетная бумага \"СВАЁ\" (3сл, 4р) 4810981001530", "туалетная бумага \"сваё\" (3сл, 4р)"),
        // Короткие числа (< 6 цифр) и бренд не снимаются: только lowercase.
        ("АИ-95", "аи-95"),
        ("1000 ЛЕПЕСТКОВ", "1000 лепестков"),
        ("256г", "256г"),
        ("нар.300г", "нар.300г"),
        ("(3сл, 4р)", "(3сл, 4р)"),
        ("РЖ.КРАЙ", "рж.край"),
        // Fallback: имя только из мусора/кода или без букв после очистки — нормализованный оригинал.
        ("*3455614", "*3455614"),
        ("2417268000006", "2417268000006"),
        ("*345", "*345"),
        // Ведущий мусор (*, #, №) и код снимаются целиком, повторные комбинации — тоже.
        ("№ 2417268000006 хлеб", "хлеб"),
        ("**##№№ 2417268000006 хлеб", "хлеб"),
        // Хвостовой код и кластер хвостовых кодов через пробел; граница 5/6 цифр.
        ("пирог 123456", "пирог"),
        ("пирог 12345", "пирог 12345"),
        ("пирог 123456 789012", "пирог"),
        // Зафиксированные ограничения: дефис/запятая внутри номера не распознаются,
        // хвостовой код, примыкающий к дефису, консервативно не снимается.
        ("241-7268000006 хлеб", "241-7268000006 хлеб"),
        ("хлеб 241-7268000006", "хлеб 241-7268000006"),
        ("хлеб 123456, 789012", "хлеб 123456,"),
        // Хвостовой мусор не снимается; 5-значный сосед не мешает снятию хвостового кода.
        ("хлеб *", "хлеб *"),
        ("хлеб 12345 789012", "хлеб 12345"),
        // Код в середине названия — вне правила (зафиксированное ограничение).
        ("хлеб 123456 пирог", "хлеб 123456 пирог"),
        ("хлеб 2417268000006 пирог с вишней", "хлеб 2417268000006 пирог с вишней"),
        // Lowercase + trim + схлопывание пробелов: кейс с ведущими/хвостовыми и строкой
        // из нескольких пробелов — он же ловит дрейф regex схлопывания пробелов в SQL-копии.
        ("  МОЛОКО  3.2%  ", "молоко 3.2%"),
    ];

    /// <summary>
    /// Тот же <see cref="Cases"/> в форме, которую принимает xUnit <c>MemberData</c>
    /// (xUnit 2.5 требует <c>IEnumerable&lt;object[]&gt;</c>). Проекция, а не второй список:
    /// ожидания по-прежнему живут только в <see cref="Cases"/>.
    /// </summary>
    public static IEnumerable<object[]> TheoryCases =>
        Cases.Select(c => new object[] { c.Input, c.Expected });
}
