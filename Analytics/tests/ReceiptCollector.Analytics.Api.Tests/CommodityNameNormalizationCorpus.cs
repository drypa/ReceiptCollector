namespace ReceiptCollector.Analytics.Api.Tests;

/// <summary>
/// Golden corpus правила очистки названий товаров (ADR-034 п. 1; задача T-03).
/// <para>
/// Единственный источник кейсов <c>(сырое имя, ожидаемый ключ)</c>. Ожидания здесь не
/// дублируются: новые кейсы добавляются только в этот файл.
/// </para>
/// <para>
/// Состав: все строки таблицы примеров ADR-034 п. 1, границы правила (5/6 цифр,
/// кластеры хвостовых кодов, ведущий мусор <c>*#№</c>, fallback «имя только из кода»),
/// зафиксированные ограничения (дефис и запятая внутри номера, код в середине) и
/// маркерное правило <c>«N: код»</c> (добавлено 2026-11-12 после применения миграции).
/// </para>
/// <para>
/// Деление на два списка: <see cref="MigrationEraCases"/> — кейсы, которые воспроизводит
/// SQL-копия правила в миграции <c>20261109120000</c> (она заморожена: миграция уже
/// применена на проде и не переписывается); <see cref="MarkerPrefixCases"/> — кейсы более
/// нового C-правила, которые frozen-копия не воспроизводит. Паритетный тест миграции
/// (<c>PrecategorizedNormalizedNameMigrationTests</c>) сверяется только с
/// <see cref="MigrationEraCases"/>; тесты нормализатора — со всеми <see cref="Cases"/>.
/// </para>
/// </summary>
internal static class CommodityNameNormalizationCorpus
{
    /// <summary>
    /// Кейсы правила «эры миграции» (raw-SQL-копия в <c>20261109120000</c> обязана давать
    /// те же результаты): источник данных для паритетного теста миграции.
    /// </summary>
    public static IReadOnlyList<(string Input, string Expected)> MigrationEraCases { get; } =
    [
        // Четыре примера из задачи (ADR-034 п. 1): ведущий EAN/артикул и хвостовой EAN снимаются,
        // «смысловые» короткие числа (256г, (3сл, 4р)) сохраняются.
        ("2417268000006 ПИРОГ С ВИШНЕЙ ПО РЕ", "пирог с вишней по ре"),
        ("2444436000001 СЕТ ДУЭТ 256г", "сет дуэт 256г"),
        ("*3455614 РЖ.КРАЙ Хлеб нар.300г", "рж.край хлеб нар.300г"),
        ("2195738 Туалетная бумага \"СВАЁ\" (3сл, 4р) 4810981001530", "туалетная бумага \"сваё\" (3сл, 4р)"),
        // Короткие числа (< 6 цифр) и бренд не снимаются: только lowercase.
        ("АИ-95", "аи-95"),
        ("1000 ЛЕПЕСТКОВ", "1000 лепестков"),
        ("256г", "256г"),
        ("нар.300г", "нар.300г"),
        ("(3сл, 4р)", "(3сл, 4р)"),
        ("РЖ.КРАЙ", "рж.край"),
        // Fallback: имя только из мусора/кода или без букв после очистки — нормализованный оригинал.
        ("*3455614", "*3455614"),
        ("2417268000006", "2417268000006"),
        ("*345", "*345"),
        // Ведущий мусор (*, #, №) и код снимаются целиком, повторные комбинации — тоже.
        ("№ 2417268000006 хлеб", "хлеб"),
        ("**##№№ 2417268000006 хлеб", "хлеб"),
        // Хвостовой код и кластер хвостовых кодов через пробел; граница 5/6 цифр.
        ("пирог 123456", "пирог"),
        ("пирог 12345", "пирог 12345"),
        ("пирог 123456 789012", "пирог"),
        // Зафиксированные ограничения: дефис/запятая внутри номера не распознаются,
        // хвостовой код, примыкающий к дефису, консервативно не снимается.
        ("241-7268000006 хлеб", "241-7268000006 хлеб"),
        ("хлеб 241-7268000006", "хлеб 241-7268000006"),
        ("хлеб 123456, 789012", "хлеб 123456,"),
        // Хвостовой мусор не снимается; 5-значный сосед не мешает снятию хвостового кода.
        ("хлеб *", "хлеб *"),
        ("хлеб 12345 789012", "хлеб 12345"),
        // Код в середине названия — вне правила (зафиксированное ограничение).
        ("хлеб 123456 пирог", "хлеб 123456 пирог"),
        ("хлеб 2417268000006 пирог с вишней", "хлеб 2417268000006 пирог с вишней"),
        // Lowercase + trim + схлопывание пробелов: кейс с ведущими/хвостовыми и строкой
        // из нескольких пробелов — он же ловит дрейф regex схлопывания пробелов в SQL-копии.
        ("  МОЛОКО  3.2%  ", "молоко 3.2%"),
    ];

    /// <summary>
    /// Маркерное правило (добавлено 2026-11-12, после применения миграции на проде):
    /// ведущий POS-маркер «число[знак *#№]:» и следующее сразу за ним число (артикул)
    /// снимаются независимо от длины числа — в реальных данных встречаются 5-значные
    /// артикулы (<c>7: 38227 СПп Хлеб СЛОБОДСКОЙ 500г</c>). Маркер без числа не снимается.
    /// Эти кейсы НЕ входят в паритетный тест миграции (SQL-копия заморожена).
    /// </summary>
    public static IReadOnlyList<(string Input, string Expected)> MarkerPrefixCases { get; } =
    [
        // Четыре примера из эксплуатации: маркер + артикул сняты, название сохранено.
        ("7: 4119096 ЩЕД.ГОД Батон НАРЕЗНОЙ нар.40", "щед.год батон нарезной нар.40"),
        ("7*: 4046989 R.SP.Шок.КАР.МУСС.МИНД.мол.1", "r.sp.шок.кар.мусс.минд.мол.1"),
        ("7: 38227 СПп Хлеб СЛОБОДСКОЙ 500г", "спп хлеб слободской 500г"),
        ("6: 78009545 СПп Хлеб СОЛОДОВЫЙ 300г", "спп хлеб солодовый 300г"),
        // 5-значный артикул после маркера — код (в отличие от 5-значного без маркера).
        ("7: 12345 хлеб", "хлеб"),
        // Маркер с 6+ значным числом снимается целиком вместе с артикулом.
        ("123456: 789012 хлеб", "хлеб"),
        // Маркер в комбинации с ведущим мусором и другими знаками прикрепления.
        ("*7: 12345 хлеб", "хлеб"),
        ("3#: 12345 хлеб", "хлеб"),
        // Маркер без числа не снимается (консервативно); маркер + код без названия — fallback.
        ("7: хлеб", "7: хлеб"),
        ("7: 4119096", "7: 4119096"),
    ];

    /// <summary>
    /// Все кейсы текущего C-правила (migration-era + маркерные) — источник для тестов
    /// нормализатора.
    /// </summary>
    public static IReadOnlyList<(string Input, string Expected)> Cases =>
    [
        .. MigrationEraCases,
        .. MarkerPrefixCases,
    ];

    /// <summary>
    /// Тот же <see cref="Cases"/> в форме, которую принимает xUnit <c>MemberData</c>
    /// (xUnit 2.5 требует <c>IEnumerable&lt;object[]&gt;</c>). Проекция, а не второй список:
    /// ожидания по-прежнему живут только в списках выше.
    /// </summary>
    public static IEnumerable<object[]> TheoryCases =>
        Cases.Select(c => new object[] { c.Input, c.Expected });
}
